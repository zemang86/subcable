// Converts landing-point photos into web-sized WebP and bakes a manifest into
// src/data/landingPointImages.ts. Run after dropping new images:
//
//   node scripts/import-landing-images.mjs
//
// Source (drop zone, NOT served):   assets/landing-points/<landing-point-id>/*
// Output (served, committed):       public/images/landing-points/<id>/<n>.webp
//
// The sources are 2000px+ screenshots; the card renders them ~400px wide, so
// shipping the originals would put ~100MB into out/ and the Electron installer.
// Only the WebP output is committed — see assets/landing-points/README.md.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, "..");
const SRC_DIR = path.join(REPO, "assets/landing-points");
const OUT_DIR = path.join(REPO, "public/images/landing-points");
const MANIFEST = path.join(REPO, "src/data/landingPointImages.ts");

// The expanded card is 439px wide with 20px padding → a 399px content box.
// 1000px covers a 2x kiosk panel with room to spare.
const MAX_WIDTH = 1000;
const QUALITY = 82;

const SOURCE_EXT = new Set([".png", ".jpg", ".jpeg", ".webp"]);

/** Read intrinsic dimensions straight from the file header. */
function readSize(file) {
  const fd = fs.openSync(file, "r");
  const buf = Buffer.alloc(32);
  fs.readSync(fd, buf, 0, 32, 0);
  fs.closeSync(fd);
  // PNG: IHDR width/height are big-endian u32 at byte 16.
  if (buf.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
    return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  }
  // Anything else (JPEG/WebP): let cwebp's own report tell us post-encode.
  return null;
}

/** Parse "Dimension: 1000 x 578" out of cwebp's stderr summary. */
function sizeFromCwebp(log) {
  const m = /Dimension:\s*(\d+)\s*x\s*(\d+)/.exec(log);
  return m ? { w: Number(m[1]), h: Number(m[2]) } : null;
}

// image.png before "image copy.png" before "image copy 2.png" — shortest name
// first is the paste order macOS produces, so [0] is the original drop.
function dropOrder(a, b) {
  return a.length - b.length || a.localeCompare(b);
}

function main() {
  if (!fs.existsSync(SRC_DIR)) {
    console.error(`No source dir: ${SRC_DIR}`);
    process.exit(1);
  }

  fs.rmSync(OUT_DIR, { recursive: true, force: true });

  const manifest = {};
  let srcBytes = 0;
  let outBytes = 0;
  let converted = 0;
  const empty = [];

  for (const id of fs.readdirSync(SRC_DIR).sort()) {
    const dir = path.join(SRC_DIR, id);
    if (!fs.statSync(dir).isDirectory()) continue;

    const files = fs
      .readdirSync(dir)
      .filter((f) => SOURCE_EXT.has(path.extname(f).toLowerCase()))
      .sort(dropOrder);

    if (files.length === 0) {
      empty.push(id);
      continue;
    }

    fs.mkdirSync(path.join(OUT_DIR, id), { recursive: true });
    const entries = [];

    files.forEach((file, i) => {
      const src = path.join(dir, file);
      // Rename on the way out: the drop names have spaces ("image copy 2.png")
      // and would need URL-encoding in every consumer.
      const outName = `${i + 1}.webp`;
      const out = path.join(OUT_DIR, id, outName);

      const log = execFileSync(
        "cwebp",
        ["-q", String(QUALITY), "-resize", String(MAX_WIDTH), "0", src, "-o", out],
        { encoding: "utf-8", stdio: ["ignore", "pipe", "pipe"] }
      );

      const srcSize = readSize(src);
      const size = sizeFromCwebp(log) ??
        (srcSize
          ? {
              w: Math.min(MAX_WIDTH, srcSize.w),
              h: Math.round((Math.min(MAX_WIDTH, srcSize.w) / srcSize.w) * srcSize.h),
            }
          : { w: MAX_WIDTH, h: Math.round(MAX_WIDTH / 1.73) });

      srcBytes += fs.statSync(src).size;
      outBytes += fs.statSync(out).size;
      converted++;

      entries.push({
        src: `/images/landing-points/${id}/${outName}`,
        width: size.w,
        height: size.h,
      });
    });

    manifest[id] = entries;
  }

  const header = `// AUTO-GENERATED by scripts/import-landing-images.mjs — do not edit by hand.
// Sources live in assets/landing-points/<id>/ (not served); this maps each
// landing-point id to its web-sized WebP renditions, in drop order.
// Re-run \`node scripts/import-landing-images.mjs\` after adding images.

export type LandingPointImage = {
  /** Path under public/, ready for <img src>. */
  src: string;
  width: number;
  height: number;
};

/** Landing-point id -> its photos. Ids with no photo are simply absent. */
export const LANDING_POINT_IMAGES: Record<string, LandingPointImage[]> = `;

  fs.writeFileSync(MANIFEST, header + JSON.stringify(manifest, null, 2) + ";\n");

  const mb = (b) => (b / 1048576).toFixed(1);
  console.log(
    `${converted} image(s) across ${Object.keys(manifest).length} landing point(s)`
  );
  console.log(`  ${mb(srcBytes)} MB source -> ${mb(outBytes)} MB webp`);
  if (empty.length) {
    console.log(`  no image yet (${empty.length}): ${empty.join(", ")}`);
  }
  console.log(`Wrote ${path.relative(REPO, MANIFEST)}`);
}

main();
